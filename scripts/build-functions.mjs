// Bundles each Edge Function in supabase/functions-src/ (plus the shared app
// code it imports) into the single file Supabase deploys:
// supabase/functions/<name>/index.ts. Run `npm run functions:build` after
// changing either. `--check` fails if a committed bundle is out of date (CI).
import { build } from 'esbuild'
import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const srcDir = path.join(root, 'supabase/functions-src')
const check = process.argv.includes('--check')

const appAlias = {
  name: 'app-alias',
  setup(b) {
    b.onResolve({ filter: /^@\// }, async (args) => {
      const res = await b.resolve('./' + args.path.slice(2), { resolveDir: path.join(root, 'src'), kind: args.kind })
      return res.errors.length ? { errors: res.errors } : { path: res.path }
    })
    // Deno resolves these itself at deploy time.
    b.onResolve({ filter: /^npm:/ }, (args) => ({ path: args.path, external: true }))
  },
}

let stale = 0
for (const file of (await readdir(srcDir)).filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts'))) {
  const name = file.replace(/\.ts$/, '')
  const out = await build({
    entryPoints: [path.join(srcDir, file)],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    mainFields: ['module', 'main'],
    legalComments: 'none',
    plugins: [appAlias],
    banner: { js: `// GENERATED by \`npm run functions:build\` from supabase/functions-src/${file}. Do not edit by hand.\n// To deploy from the Supabase dashboard, paste this whole file into the function editor.` },
  })
  const code = out.outputFiles[0].text
  const target = path.join(root, 'supabase/functions', name, 'index.ts')
  const current = await readFile(target, 'utf8').catch(() => '')
  if (current === code) continue
  if (check) {
    console.error(`${path.relative(root, target)} is out of date. Run npm run functions:build and commit the result.`)
    stale++
    continue
  }
  await mkdir(path.dirname(target), { recursive: true })
  await writeFile(target, code)
  console.log(`wrote ${path.relative(root, target)} (${(code.length / 1024).toFixed(1)} KB)`)
}
if (stale) process.exit(1)
